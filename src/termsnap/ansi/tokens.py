"""
Лексический разбор потока терминала: на какие куски делится текст с управляющими последовательностями.
"""

import re

#: Один кусок потока. Имя сработавшей группы (``match.lastgroup``) говорит, что это:
#:
#: - ``osc`` - команда ``ESC ] ... BEL`` (заголовок окна, гиперссылки): в текст не попадает;
#: - ``final`` - последовательность ``ESC [ <параметры> <буква>`` (CSI): параметры в группе ``params``;
#: - ``control`` - один из управляющих символов, меняющих положение курсора;
#: - ``text`` - обычный текст;
#: - остальные ветки - прочие последовательности и управляющие символы, которые просто отбрасываются.
TOKEN = re.compile(
    r"""
    (?P<osc>\x1b\][^\x07\x1b]*(?:\x07|\x1b\\)?)        # OSC: заголовок окна, гиперссылки
    | \x1b\[(?P<params>[0-?]*)[ -/]*(?P<final>[@-~])   # CSI
    | (?P<control>[\r\n\b\t])
    | (?P<text>[^\x00-\x1f\x7f]+)
    | \x1b[ -/]*[0-~]?                                 # прочие последовательности с ESC
    | [\x00-\x1f\x7f]                                  # остальные управляющие символы
    """,
    re.VERBOSE,
)


def number(part: str) -> int:
    """
    Число из параметра последовательности; пустой или нечисловой параметр означает 0 (так читает терминал).
    """
    return int(part) if part.isdigit() else 0
