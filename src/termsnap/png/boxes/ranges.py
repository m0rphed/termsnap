#: Блочные элементы U+2580-259F (половины, доли, штриховка, квадранты).
BLOCK_ELEMENTS = range(0x2580, 0x25A0)

#: Шрифт Брайля U+2800-28FF: 256 сочетаний из восьми точек.
BRAILLE = range(0x2800, 0x2900)
