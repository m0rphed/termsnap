"""
Пропорции рисования: как размеры мелких деталей выводятся из размера шрифта и метрик строки.

Все числа, которые определяют вид картинки и не заданы пользователем, собраны здесь. Детали считаются от размера
шрифта в пикселях, поэтому при смене ``font_size`` и ``scale`` картинка остается подобной.
"""

import math

#: Значения параметров ``render_image`` по умолчанию. Размер шрифта и поля задаются в пикселях "как на экране", а
#: ``scale`` во сколько раз картинка подробнее (при 2 текст четкий на дисплеях высокой плотности); межстрочный
#: коэффициент 1.25 дает строкам воздух, но рамки при этом все равно смыкаются (их рисует сама библиотека).
DEFAULT_FONT_SIZE = 14
DEFAULT_SCALE = 2
DEFAULT_PADDING = 16
DEFAULT_LINE_SPACING = 1.25

#: Доля цвета текста в тусклом (SGR 2) тексте; остальное - цвет фона.
DIM_SHARE = 0.6

#: Символ, по ширине которого считается клетка: в моноширинном шрифте все символы одной ширины, "M" - самая
#: показательная.
CELL_MEASURE_CHAR = "M"

#: Разрешение, которое считается "экранным": при масштабе ``scale`` в PNG записывается ``SCREEN_DPI * scale`` точек
#: на дюйм, и Word с браузером показывают картинку в размере "как на экране".
SCREEN_DPI = 96

#: Отключение лигатур для шрифтов с лигатурами (``fi``, ``->``, ``!=`` не должны сливаться в один знак: терминал
#: рисует каждый символ в своей клетке). Работает только при наличии библиотеки raqm в сборке Pillow.
NO_LIGATURES = ["-liga", "-clig", "-calt"]

#: Во сколько раз толщина линии (подчеркивание, зачеркивание, рамки) меньше размера шрифта в пикселях.
_THICKNESS_DIVISOR = 14

#: Во сколько раз сдвиг второго прохода при имитации жирности меньше размера шрифта.
_BOLD_SHIFT_DIVISOR = 16

#: Подчеркивание лежит ниже базовой линии на треть спуска, но не ближе двух пикселей.
_UNDERLINE_MIN_OFFSET = 2
_UNDERLINE_DESCENT_DIVISOR = 3

#: Зачеркивание лежит выше базовой линии на эту долю подъема: примерно на середине строчных букв.
_STRIKE_ASCENT_SHARE = 0.3


def line_thickness(size: int) -> int:
    """
    Толщина тонкой линии в пикселях для шрифта размера ``size``; не меньше одного пикселя.
    """
    return max(1, size // _THICKNESS_DIVISOR)


def bold_shift(size: int) -> int:
    """
    На сколько пикселей сдвинут второй проход, которым имитируется жирность (текст рисуется дважды); не меньше одного.
    """
    return max(1, size // _BOLD_SHIFT_DIVISOR)


def underline_offset(descent: int) -> int:
    """
    На сколько пикселей верх линии подчеркивания ниже базовой линии.
    """
    return max(_UNDERLINE_MIN_OFFSET, descent // _UNDERLINE_DESCENT_DIVISOR)


def strike_offset(ascent: int) -> int:
    """
    На сколько пикселей верх линии зачеркивания выше базовой линии.
    """
    return round(ascent * _STRIKE_ASCENT_SHARE)


def row_height(ascent: int, descent: int, line_spacing: float) -> int:
    """
    Высота строки: высота шрифта (подъем + спуск), умноженная на межстрочный коэффициент, округленная вверх.
    """
    return math.ceil((ascent + descent) * line_spacing)
